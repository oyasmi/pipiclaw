const quarantined = new Set(["S-net-02"]);

export function metadataForCase(id: string, source: string, description: string): EvalCaseMetadata {
	const family = caseFamilyMap[id];
	if (!family)
		return {
			version: 1,
			family: id,
			domain: "coding",
			scope: "component",
			tags: ["unregistered"],
			owner: "case-author",
			lifecycle: "draft",
			source: { kind: "capability", ref: source },
			contract: {
				objective: description,
				acceptance: ["declared graders pass"],
				forbiddenEffects: ["claim-only completion"],
			},
			dependencies: [],
		};
	const descriptor = familyCatalog.find((entry) => entry.id === family)!;
	const isCore = (coreRepresentativeIds as readonly string[]).includes(id);
	return {
		version: 1,
		family,
		domain: descriptor.domain,
		scope: "journey",
		tags: [isCore ? "core" : descriptor.core ? "legacy-variant" : "extended", "natural"],
		owner: "runtime-maintainers",
		lifecycle: quarantined.has(id) ? "quarantine" : isCore ? "candidate" : "regression",
		source: {
			kind: source.includes("reported") || source.includes("review") ? "incident" : "product-contract",
			ref: source,
		},
		contract: {
			objective: description,
			acceptance: ["全部 acceptance grader 通过，且证据完整"],
			forbiddenEffects: ["不得以成功宣言代替可观察结果", "不得违反 hard-invariant"],
		},
		dependencies: caseDependencyOverrides[id] ?? descriptor.dependencies,
	};
}

export function validateCatalog(caseIds: string[]): void {
	const missing = caseIds.filter((id) => !caseFamilyMap[id]);
	if (missing.length)
		throw new Error(`Case catalog is missing: ${missing.join(", ")}. Add family metadata before running.`);
	const unknown = Object.keys(caseFamilyMap).filter((id) => !caseIds.includes(id));
	if (unknown.length)
		throw new Error(`Case catalog references missing cases: ${unknown.join(", ")}. Remove stale entries.`);
}
